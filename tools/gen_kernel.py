#!/usr/bin/env python3
"""Writes src/kernel.c: the band-limited step and interpolation tables.

Both come from one Kaiser-windowed sinc with its cutoff at the host Nyquist
frequency, measured in host samples, so one table serves every host rate.
32 taps and 64 phases with linear interpolation between phases keep folded
images below -89 dB for a 26.04 kHz staircase rendered at 48 kHz (the
residue at that level is the 12-bit quantisation itself), the passband flat
to 0.417 of the host rate and the stopband 82 dB down by 0.6 of it.
"""
import sys
import numpy as np

TAPS = 32
PHASES = 64
BETA = 8.0
FINE = 4096


def kernel():
    m = TAPS * FINE
    tau = (np.arange(m + 1) - m / 2) / FINE
    h = np.sinc(tau) * np.kaiser(m + 1, BETA)
    s = np.concatenate([[0.0], np.cumsum((h[1:] + h[:-1]) / 2) / FINE])
    return tau, h, s / s[-1]


def tables():
    tau, h, s = kernel()

    def at(arr, t):
        return np.interp(t, tau, arr, left=arr[0], right=arr[-1])

    step = np.zeros((PHASES + 1, TAPS))
    sinc = np.zeros((PHASES + 1, TAPS))
    for p in range(PHASES + 1):
        f = p / PHASES
        j = np.arange(TAPS)
        step[p] = at(s, j - TAPS / 2 + f)
        row = at(h, f + TAPS / 2 - 1 - j)
        sinc[p] = row / row.sum()
    return step, sinc


def literal(v):
    if abs(v) < 1e-12:
        return "0.0f"
    s = f"{v:.9g}"
    if "." not in s and "e" not in s:
        s += ".0"
    return s + "f"


def emit(name, t):
    lines = [f"const float {name}[{t.size}] = {{"]
    for row in t:
        lines.append("    " + ", ".join(literal(v) for v in row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main(out):
    step, sinc = tables()
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_kernel.py. Do not edit. */\n")
        f.write('#include "internal.h"\n\n')
        f.write(f"#if MD12_TAPS != {TAPS} || MD12_PHASES != {PHASES}\n")
        f.write("#error kernel tables out of step with internal.h\n#endif\n\n")
        f.write(emit("md12_step_tab", step) + "\n\n")
        f.write(emit("md12_sinc_tab", sinc) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/kernel.c")
