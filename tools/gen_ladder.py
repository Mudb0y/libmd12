#!/usr/bin/env python3
"""Writes src/ladder.c: one stage of the SSM2044 at any cutoff.

The chip's four poles are matched, so one table serves every stage. A row
holds a one-pole low-pass whose pole is the analogue pole mapped exactly and
whose three-tap numerator is chosen, with DC exact, to minimise the worst dB
error of all four stages in series against the analogue filter, up to 0.42
of the host rate. Rows run in eighths of an octave of cutoff over host rate;
neighbouring rows start from each other's solution, so the coefficients
change smoothly and can be interpolated as the filter sweeps. The worst
error over the whole table is printed and must stay below 0.3 dB.
"""
import sys

import numpy as np
from scipy.optimize import minimize

LO, HI, STEPS = -14, 2, 8
TOP = 0.42


def cascade_error(x, r):
    wc = 2 * np.pi * r
    p = np.exp(-wc)
    w = np.linspace(1e-4, TOP * 2 * np.pi, 400)
    z = np.exp(-1j * w)
    b = np.array([(1 - p) - x[0] - x[1], x[0], x[1]])
    hd = (np.polyval(b[::-1], z) / (1 - p * z)) ** 4
    ha = (1 / (1 + 1j * w / wc)) ** 4
    keep = 20 * np.log10(np.abs(ha)) > -50
    if not keep.any():
        return 0.0
    return np.max(np.abs(20 * np.log10(np.abs(hd[keep]) + 1e-300) - 20 * np.log10(np.abs(ha[keep]))))


def main(out):
    rows, worst = [], 0.0
    x = None
    for k in range((HI - LO) * STEPS + 1):
        r = 2.0 ** (LO + k / STEPS)
        p = np.exp(-2 * np.pi * r)
        starts = [np.array([(1 - p) / 3, (1 - p) / 3])]
        if x is not None:
            starts.insert(0, x)
        best = None
        for s0 in starts:
            res = minimize(lambda v: cascade_error(v, r), s0, method="Nelder-Mead",
                           options={"xatol": 1e-11, "fatol": 1e-7, "maxiter": 6000})
            if best is None or res.fun < best.fun - 1e-6:
                best = res
        x = best.x
        worst = max(worst, best.fun)
        rows.append((p, (1 - p) - x[0] - x[1], x[0], x[1]))
    if worst > 0.3:
        raise SystemExit(f"ladder table: worst error {worst:.3f} dB")
    print(f"gen_ladder: {len(rows)} rows, worst cascade error {worst:.3f} dB")
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_ladder.py. Do not edit. */\n")
        f.write('#include "internal.h"\n\n')
        f.write(f"#if MD12_LADDER_LO != {LO} || MD12_LADDER_STEPS != {STEPS} || MD12_LADDER_ROWS != {len(rows)}\n")
        f.write("#error ladder table out of step with internal.h\n#endif\n\n")
        f.write("/* Per row: pole, then the three numerator taps. */\n")
        f.write(f"const float md12_ladder_tab[{len(rows)}][4] = {{\n")
        for row in rows:
            f.write("    {" + ", ".join(f"{v:.9e}f" for v in row) + "},\n")
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/ladder.c")
